import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { get } from '@dotenvx/dotenvx';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** @param {Record<string, string | undefined>} [env] */
export function environmentMode(env = process.env) {
  const mode = env['VIENNAFLOW_ENV'] ?? (env['VERCEL_ENV'] === 'preview' ? 'staging' : env['VERCEL_ENV']) ?? 'development';
  if (mode !== 'development' && mode !== 'staging' && mode !== 'production') {
    throw new Error('VIENNAFLOW_ENV must be development, staging, or production');
  }
  return mode;
}

/** @param {'development' | 'staging' | 'production'} [mode] */
export function environmentFile(mode = environmentMode()) {
  return path.join(root, mode === 'development' ? '.env' : `.env.${mode}`);
}

/** @param {string} name */
export function managedValue(name) {
  // Explicit platform/CI values win. No fallback from one environment file to another.
  const configured = process.env[name];
  if (configured !== undefined && !configured.startsWith('encrypted:')) return configured;
  try {
    const value = get(name, { path: environmentFile(), strict: true });
    return value?.startsWith('encrypted:') ? undefined : value;
  }
  catch { return undefined; }
}

/** @param {(name: string) => string | undefined} [read] @param {'development' | 'staging' | 'production'} [mode] */
export function browserEnvironment(read = managedValue, mode = environmentMode()) {
  const required = (/** @type {string} */ name) => {
    const value = read(name);
    if (!value || value.startsWith('encrypted:')) throw new Error(`Missing or undecrypted configuration: ${name}`);
    return value;
  };
  const apiKey = required('GOOGLE_MAPS_API_KEY');
  const mapId = required('GOOGLE_MAPS_MAP_ID');
  const url = required('SUPABASE_URL');
  const anonKey = required('SUPABASE_ANON_KEY');
  let parsed;
  try { parsed = new URL(url); } catch { throw new Error('SUPABASE_URL must be a valid URL'); }
  if (parsed.username || parsed.password ||
    (parsed.protocol !== 'https:' && !(parsed.protocol === 'http:' && ['localhost', '127.0.0.1'].includes(parsed.hostname)))) {
    throw new Error('SUPABASE_URL must use HTTPS, or HTTP for localhost');
  }
  let role;
  try { role = JSON.parse(Buffer.from(anonKey.split('.')[1], 'base64url').toString('utf8')).role; } catch { /* Publishable keys need not be JWTs. */ }
  if (anonKey.startsWith('sb_secret_') || role === 'service_role') throw new Error('SUPABASE_ANON_KEY must be a browser-safe public key');
  return { production: mode === 'production', environment: mode, googleMaps: { apiKey, mapId }, supabase: { url, anonKey } };
}

/** @param {ReturnType<typeof browserEnvironment>} configuration */
export function serializeBrowserEnvironment(configuration) {
  return `// Generated by scripts/generate-env.js. Do not edit directly.\nexport const environment = ${JSON.stringify(configuration, null, 2)};\n`;
}
